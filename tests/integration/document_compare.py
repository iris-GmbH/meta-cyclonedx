"""Comparison helpers for documents produced by different regenerations.

`canonicalize` is used *only* to compare documents regenerated from equal
content (run R3): it removes exactly the fields the adapter stamps
fresh on every generation — document serial numbers (the CycloneDX
serials and every UUIDv4 bom-ref or urn:cdx reference derived from them),
statement and tool timestamps, the build DATETIME inside the image
version, and the working tree's git state at export time (the layer
external-reference rev/modified properties and the checkout baked into
those urls).
Cache-reuse comparisons (R2, R4) stay byte-level and must never route
through this module: a canonicalizing comparison could launder a stale
artifact into "reused".

`first_difference` reports where two (canonicalized) documents diverge,
so a failed comparison names the location instead of dumping documents.
"""

from __future__ import annotations

import re

#: UUIDv4-shaped strings — CycloneDX serial numbers and bom-refs. Masked
#: *uniformly*, so cross-references (a VEX urn:cdx pointer naming the
#: SBOM's serial and a component's bom-ref) keep comparing equal.
UUID = re.compile(
    r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
)
UUID_PLACEHOLDER = "<uuid>"

#: Field names carrying generation-time timestamps (metadata.statement
#: timestamps, citation/tool timestamps).
TIMESTAMP_KEYS = frozenset({"timestamp"})

#: `properties` entries describing the harness working tree, not document
#: content: the layer revision and its dirty flag at export time. The
#: matrix spans commits, so a cold run recorded under one commit must still compare equal to a
#: regenerated run recorded under another.
GIT_STATE_PROPERTIES = frozenset({"yocto:layer:rev", "yocto:layer:is_modified"})


#: The same git state's second carrier: layer external references spell
#: the checkout into their url — `<remote>@<rev>` plus a ` -- modified`
#: flag while the tree is dirty (R3 dirties it by design). Normalized
#: only on items whose yocto:layer:* properties mark them as layer
#: references, so a package's own SRCREV vcs url keeps its teeth.
LAYER_GIT_URL = re.compile(r"(?:@[0-9a-fA-F]{7,40})?(?: -- modified)?$")

#: BitBake's build stamp as it rides the image component's version
#: (`<DISTRO_VERSION>-<DATETIME>`): regenerated by any run that
#: re-parses recipes, so R3's mutated run mints a fresh one.
BUILD_STAMP = re.compile(r"(?<=.)-\d{14}$")
BUILD_STAMP_PLACEHOLDER = "-<DATETIME>"


def _is_layer_reference(item):
    return isinstance(item, dict) and any(
        isinstance(prop, dict)
        and str(prop.get("name", "")).startswith("yocto:layer:")
        for prop in item.get("properties", [])
    )


def canonicalize(value):
    """A copy of *value* with the per-generation volatiles normalized."""
    if isinstance(value, dict):
        layer = _is_layer_reference(value)
        result = {
            key: canonicalize(item)
            for key, item in value.items()
            if key not in TIMESTAMP_KEYS
        }
        if layer and isinstance(result.get("url"), str):
            result["url"] = LAYER_GIT_URL.sub("", result["url"])
        return result
    if isinstance(value, list):
        return [
            canonicalize(item)
            for item in value
            if not (
                isinstance(item, dict)
                and set(item) <= {"name", "value"}
                and item.get("name") in GIT_STATE_PROPERTIES
            )
        ]
    if isinstance(value, str):
        value = UUID.sub(UUID_PLACEHOLDER, value)
        return BUILD_STAMP.sub(BUILD_STAMP_PLACEHOLDER, value)
    return value


def first_difference(a, b, path: str = "$") -> str | None:
    """A compact description of where *a* and *b* differ, or None."""
    if a == b:
        return None
    if isinstance(a, dict) and isinstance(b, dict):
        for key in sorted(set(a) | set(b), key=str):
            location = f"{path}.{key}"
            if key not in a:
                return f"{location}: absent vs {_short(b[key])}"
            if key not in b:
                return f"{location}: {_short(a[key])} vs absent"
            difference = first_difference(a[key], b[key], location)
            if difference:
                return difference
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return f"{path}: {len(a)} entries vs {len(b)}"
        for index, (left, right) in enumerate(zip(a, b)):
            difference = first_difference(left, right, f"{path}[{index}]")
            if difference:
                return difference
    return f"{path}: {_short(a)} vs {_short(b)}"


def _short(value, limit: int = 160) -> str:
    text = repr(value)
    return text if len(text) <= limit else text[: limit - 3] + "..."
